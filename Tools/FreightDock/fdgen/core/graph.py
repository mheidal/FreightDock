"""Graph: collects nodes, pins and links for one function body and renders them as Blueprint clipboard
text (T3D). Every node is labelled with its name (NodeComment), which is how install specs and ImportFunction find
nodes again. GUIDs come from one process-wide counter.
"""
import itertools
from fdgen.core.types import BOOL


_ids = itertools.count(1)


def guid():
    return f"{next(_ids):032X}"


class Graph:
    def __init__(self):
        self.nodes = []      # (name, cls, props, x, y, pins)
        self.pinids = {}     # (node, pin) -> guid
        self.links = {}      # (node, pin) -> [(node, pin)]
        self.alias = {}      # (node, pin) -> (node, pin) that links to it really go to

    def node(self, name, cls, props, x, y, pins):
        """pins: list of (pinName, 'in'|'out', typeFragments, defaultOrNone)"""
        for p in pins:
            self.pinids[(name, p[0])] = guid()
        self.nodes.append((name, cls, props, x, y, pins))
        return name

    def link(self, a, b):
        """a, b: (node, pin) tuples; recorded on both ends."""
        a, b = self.alias.get(a, a), self.alias.get(b, b)
        for x, y in ((a, b), (b, a)):
            assert x in self.pinids, f"unknown pin {x}"
            self.links.setdefault(x, []).append(y)

    def call(self, name, parent, func, x, y, pins):
        return self.node(name, "/Script/BlueprintGraph.K2Node_CallFunction",
                         [f'FunctionReference=(MemberParent="{parent}",MemberName="{func}")'], x, y, pins)

    def render(self):
        out = []
        for name, cls, props, x, y, pins in self.nodes:
            out.append(f'Begin Object Class={cls} Name="{name}"')
            out += [f"   {p}" for p in props]
            # visible label, so instructions can name nodes
            out += [f'   NodeComment="{name}"', "   bCommentBubblePinned=True", "   bCommentBubbleVisible=True"]
            out.append(f"   NodePosX={x}")
            out.append(f"   NodePosY={y}")
            out.append(f"   NodeGuid={guid()}")
            for pname, direction, ptype, default in pins:
                fields = [f"PinId={self.pinids[(name, pname)]}", f'PinName="{pname}"']
                if direction == "out":
                    fields.append('Direction="EGPD_Output"')
                fields += ptype
                if default is not None:
                    fields.append(default)
                    # with no autogenerated default given, the editor takes a bool "false" for an unset pin and
                    # resets it to the function's own default (e.g. bUseGrouping back to true); naming the opposite
                    # as the autogenerated default marks the value as chosen
                    if ptype == BOOL and default in ('DefaultValue="false"', 'DefaultValue="true"'):
                        other = "true" if default == 'DefaultValue="false"' else "false"
                        fields.append(f'AutogeneratedDefaultValue="{other}"')
                linked = self.links.get((name, pname))
                if linked:
                    fields.append("LinkedTo=(" + ",".join(f"{n} {self.pinids[(n, p)]}" for n, p in linked) + ",)")
                out.append("   CustomProperties Pin (" + ",".join(fields) + ",)")
            out.append("End Object")
        return "\n".join(out) + "\n"


def local_var(scope, var):
    return f'VariableReference=(MemberScope="{scope}",MemberName="{var}")'
